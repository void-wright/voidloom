# -*- coding: utf-8 -*-
"""R4 -- every path literal an installer READS after laying resolves to a laid file.

Council #12 (2026-09-18): install.ps1 carried four consumer literals that named
files at paths the package does not lay -- `merge_config.py` and `token_doctor.py`
at the brain root (they ship under install/ and tools/), `CLAUDE.md.template` at
the package root (install/), and `install_crons.ps1`, which does not exist at all.
Each sat behind a Test-Path guard, so each failed SILENTLY: the wet run found two
before dying; the census found all four; this test finds them without executing.

THE POPULATION is derived from the installers' own text, never typed here:
    install.sh          ${BRAIN_DIR}/<rel>   ${PKG_ROOT}/<rel>   ${CLAUDE_HOME}/<rel>
    install/install.ps1 Join-Path $BrainDir "<rel>"   $PkgRoot "<rel>"   $ClaudeHome "<rel>"
    install/install_crons.sh  ${BRAIN_DIR}/<rel>   ${SELF_ROOT}/<rel>   ${CRON_DIR}/<rel>
                        (the ONE unit renderer since round-1 item 8; SELF_ROOT is the
                        package or the laid brain -- same layout -- so it is graded as
                        package-relative; CRON_DIR is SELF_ROOT/cron)
Comment lines are excluded (they are prose about the code, graded elsewhere);
user-facing `say`/`Say` strings are INCLUDED, because a help line naming a path is
believed by the person who reads it (conventions-015).

THE ORACLE is install/lay_manifest.json -- the same table lay.py executes -- read
from the tree under test. Where that tree has no manifest (the parent commit),
the oracle falls back to `git ls-files` laid by identity, and says so, so the
four literals above are still named rather than everything failing at once.

Every literal is one parametrized case, so the count of reds IS the count of
wrong literals. Two shapes, two rules:
  * FILE-shaped (a suffix): must be a manifest dst/src, or a named RUNTIME file
    (each with a one-line reason);
  * DIRECTORY-shaped: must be the parent of at least one laid entry, a named
    runtime directory, or a named optional bundled-payload probe.
An allowlist entry no installer references is itself flagged: an allowlist is
prose too.

VOIDLOOM_ROOT points the test at another tree (the parent arm); the default is
this file's own package.

This file binds the CHECKOUT (install.sh is root=null: it ships, it is not laid).
On an installed brain the whole module SKIPS with the reason (`pytestmark`) --
UNMEASURABLE, not PASS.
"""
from __future__ import annotations

import json
import os
import re
import subprocess
from pathlib import Path

import pytest

ROOT = Path(os.environ.get("VOIDLOOM_ROOT") or Path(__file__).resolve().parents[2]).resolve()
MANIFEST = ROOT / "install" / "lay_manifest.json"
SH = ROOT / "install.sh"
PS1 = ROOT / "install" / "install.ps1"
CRONS_SH = ROOT / "install" / "install_crons.sh"

pytestmark = pytest.mark.skipif(
    not SH.is_file() or not (ROOT / ".git").exists(),
    reason="NOT A CHECKOUT: %s has no install.sh/.git (install.sh is root=null: ships, not laid). "
           "Run from the package checkout or set VOIDLOOM_ROOT=<checkout>." % ROOT)

# --- the runtime allowlist: brain-relative paths that are CREATED at install/run time,
#     never laid from the package. Each carries its reason; each must be referenced.
RUNTIME_BRAIN = {
    "claude_memory.db": "the brain: cloned, initialised or attached at Step B, never laid",
    "venv": "the Tier-1 virtualenv built at Step C",
    "venv/bin/python3": "the venv interpreter (Step C, and the cron interpreter rule)",
    "logs": "runtime log directory created at Step A.1",
    "voidloom_manifest.json": "hardware manifest GENERATED per host by organs/voidloom_manifest.py (Step A.1b-i)",
    "INSTALL_RECORD": "the install record GENERATED by install.sh on every successful wet run; the ambient shape "
                      "reads it on the next (reference-host round, R1; install/write_set.json step R)",
    "INSTALL_LOG": "the append-only install log install.sh writes, one line per wet run (R1; write_set.json step R)",
}
# package-relative probes for OPTIONAL bundled payloads: present-guarded, never tracked
OPTIONAL_PKG = {
    "brain/claude_memory.db": "an optional bundled brain snapshot (resolve_brain_source)",
    "claude_memory.db": "an optional bundled brain snapshot at the package root (resolve_brain_source)",
}
# NOT allowlisted (round-1 reflection, item 6): install.ps1's `$PkgRoot "memory"` /
# "memory\*" probes. No tracked path starts with memory/ and no build step can produce
# one -- the never-ran branch VAEL recorded under #10 -- the same shape as `skills`,
# which is deferred below. Two identical shapes, one verdict: deferred, not excused.
# members of the install root ($CLAUDE_HOME): host files and the target dirs
# `commands` (root=home, commands/) is laid by lay.py and named by NO installer literal since
# install.sh's dead COMMANDS_DIR went (round-1 iteration-2 reflection, item 8); an allowlist entry
# nothing references is prose, so it carries none here.
CLAUDE_HOME_MEMBERS = {
    "memory": "the brain directory (root=brain)",
    "skills": "the skills directory (root=skills)",
    "hooks": "the host hooks directory (install.ps1 creates it; install.sh no longer touches it)",
    "commands": "the commands directory (root=home): install.ps1 STEP P places /persona-forge there "
                "(component forge; install.sh lays it through install/install_persona_forge.sh)",
    "CLAUDE.md": "the host's CLAUDE.md, written by the instructions organ behind guarded_write_text",
    "settings.json": "the host's settings.json, written by the hooks organ behind guarded_write_text",
}

SH_RE = re.compile(r"\$\{(BRAIN_DIR|PKG_ROOT|CLAUDE_HOME)\}/([A-Za-z0-9_./*-]+)")
CRONS_RE = re.compile(r"\$\{(BRAIN_DIR|SELF_ROOT|CRON_DIR)\}/([A-Za-z0-9_./*-]+)")
PS1_RE = re.compile(r"Join-Path\s+\$(BrainDir|PkgRoot|ClaudeHome)\s+['\"]([^'\"]+)['\"]")
KIND = {"BRAIN_DIR": "brain", "BrainDir": "brain", "PKG_ROOT": "pkg", "PkgRoot": "pkg",
        "CLAUDE_HOME": "home", "ClaudeHome": "home", "SELF_ROOT": "pkg", "CRON_DIR": "pkg"}


def _code_lines(path: Path, comment_prefix: str):
    for n, line in enumerate(path.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
        if line.lstrip().startswith(comment_prefix):
            continue
        yield n, line


def literals():
    """[(installer, line, kind, rel)] -- every distinct literal, from the text."""
    out, seen = [], set()
    if SH.is_file():
        for n, line in _code_lines(SH, "#"):
            for m in SH_RE.finditer(line):
                rel = m.group(2)
                while rel.endswith("/.") or rel.endswith("/"):
                    rel = rel[:-2] if rel.endswith("/.") else rel[:-1]
                key = ("install.sh", KIND[m.group(1)], rel)
                if rel and key not in seen:
                    seen.add(key); out.append(("install.sh", n, KIND[m.group(1)], rel))
    if CRONS_SH.is_file():
        for n, line in _code_lines(CRONS_SH, "#"):
            for m in CRONS_RE.finditer(line):
                rel = m.group(2)
                while rel.endswith("/.") or rel.endswith("/"):
                    rel = rel[:-2] if rel.endswith("/.") else rel[:-1]
                if m.group(1) == "CRON_DIR":
                    rel = "cron/" + rel
                key = ("install_crons.sh", KIND[m.group(1)], rel)
                if rel and key not in seen:
                    seen.add(key); out.append(("install_crons.sh", n, KIND[m.group(1)], rel))
    if PS1.is_file():
        for n, line in _code_lines(PS1, "#"):
            for m in PS1_RE.finditer(line):
                rel = m.group(2).replace("\\", "/")
                key = ("install.ps1", KIND[m.group(1)], rel)
                if key not in seen:
                    seen.add(key); out.append(("install.ps1", n, KIND[m.group(1)], rel))
    return out


def oracle():
    """(brain_dsts, pkg_srcs, note). From the manifest, else from git by identity."""
    if MANIFEST.is_file():
        doc = json.loads(MANIFEST.read_text(encoding="utf-8"))
        brain = {e["dst"] for e in doc["entries"] if e["root"] == "brain"}
        srcs = {e["src"] for e in doc["entries"]}
        return brain, srcs, "oracle: install/lay_manifest.json (%d entries)" % len(doc["entries"])
    out = subprocess.run(["git", "ls-files"], cwd=str(ROOT), capture_output=True, text=True)
    files = {f for f in out.stdout.split("\n") if f.strip()} if out.returncode == 0 else set()
    brain = {f for f in files if "/" in f and not f.startswith("persona/")}
    return brain, files, ("oracle: NO install/lay_manifest.json in %s -- fell back to git ls-files laid by "
                          "identity (%d files); this tree has no lay manifest" % (ROOT, len(files)))


BRAIN, SRCS, NOTE = oracle()
LITERALS = literals()
# A glob (`organs/*.py`, `memory\*`) names a DIRECTORY the installer sweeps, so it is
# graded as its directory part; a bare name with a suffix is a file.
FILES = [l for l in LITERALS if "*" not in l[3] and "." in l[3].rsplit("/", 1)[-1]]
DIRS = [l for l in LITERALS if l not in FILES]


def _dir_base(rel: str) -> str:
    parts = rel.split("/")
    keep = []
    for seg in parts:
        if "*" in seg:
            break
        keep.append(seg)
    return "/".join(keep)


def _dirs_laid(paths):
    d = set()
    for p in paths:
        parts = p.split("/")
        for i in range(1, len(parts)):
            d.add("/".join(parts[:i]))
    return d


BRAIN_DIRS = _dirs_laid(BRAIN)
SRC_DIRS = _dirs_laid(SRCS)


def _ident(l):
    return "%s:%d %s/%s" % (l[0], l[1], l[2], l[3])


# --- DEFERRED, NOT HIDDEN (conventions-012). install/install.ps1 is not touched in
# round 1; round 2 rewrites it as the prologue. Its known-wrong literals are the
# Council's four plus VAEL's #11 (`$PkgRoot "skills"`, the old layout's skills dir,
# in two spellings) and VAEL's #10 (`$PkgRoot "memory"`, the whole-memory payload
# dir nothing ships, in two spellings). Each is a STRICT xfail: it must FAIL today,
# and the suite goes red the moment one is fixed while still listed here -- so the
# deferral cannot outlive the defect. Any OTHER install.ps1 literal that goes red is
# a real failure. VOIDLOOM_NO_DEFERRALS=1 switches the marks off and shows the raw
# verdicts (used for the red-at-parent arm).
PS1_DEFERRED_TO_ROUND_2 = {
    "brain/merge_config.py", "pkg/CLAUDE.md.template", "brain/token_doctor.py",
    "brain/install_crons.ps1", "pkg/skills", "pkg/skills/*", "pkg/memory", "pkg/memory/*",
}
_DEFER = os.environ.get("VOIDLOOM_NO_DEFERRALS", "") != "1"


def _param(l):
    key = "%s/%s" % (l[2], l[3])
    if _DEFER and l[0] == "install.ps1" and key in PS1_DEFERRED_TO_ROUND_2:
        return pytest.param(l, id=_ident(l), marks=pytest.mark.xfail(
            strict=True, reason="DEFERRED to round 2 (install.ps1 becomes the prologue): "
                                "a known-wrong literal that must fail today"))
    return pytest.param(l, id=_ident(l))


def test_population_is_not_empty():
    assert SH.is_file(), "no install.sh at %s" % ROOT
    assert len(LITERALS) >= 10, "only %d literals found -- the extractor is wrong (%s)" % (len(LITERALS), NOTE)
    assert BRAIN, "the oracle is empty: %s" % NOTE
    print(NOTE)
    print("population: %d literals (%d file-shaped, %d directory-shaped)" % (len(LITERALS), len(FILES), len(DIRS)))


@pytest.mark.parametrize("lit", [_param(l) for l in FILES])
def test_file_literal_resolves_to_a_laid_file(lit):
    installer, line, kind, rel = lit
    if kind == "brain":
        ok = rel in BRAIN or rel in RUNTIME_BRAIN
        where = "laid under root=brain" if rel in BRAIN else ("runtime: " + RUNTIME_BRAIN.get(rel, ""))
    elif kind == "pkg":
        ok = rel in SRCS or rel in OPTIONAL_PKG
        where = "a tracked package file" if rel in SRCS else ("optional payload: " + OPTIONAL_PKG.get(rel, ""))
    else:
        ok = rel in CLAUDE_HOME_MEMBERS
        where = CLAUDE_HOME_MEMBERS.get(rel, "")
    assert ok, ("%s:%d reads %s/%s and nothing lays it there (%s). Laid names that look like it: %s"
                % (installer, line, kind, rel, NOTE,
                   sorted(p for p in (BRAIN | SRCS) if p.rsplit("/", 1)[-1] == rel.rsplit("/", 1)[-1])[:5]))
    print("%s -> %s" % (_ident(lit), where))


@pytest.mark.parametrize("lit", [_param(l) for l in DIRS])
def test_dir_literal_is_a_laid_directory(lit):
    installer, line, kind, rel = lit
    base = _dir_base(rel)
    # a suffix-less laid FILE (voidloom/voidloom, the CLI shim) is graded as a file
    if kind == "brain":
        ok = base in BRAIN_DIRS or base in BRAIN or base in RUNTIME_BRAIN
    elif kind == "pkg":
        ok = base in SRC_DIRS or base in SRCS or rel in OPTIONAL_PKG or base in OPTIONAL_PKG
    else:
        ok = base in CLAUDE_HOME_MEMBERS
    assert ok, ("%s:%d names the directory %s/%s and no laid entry lives under it (%s). Laid directories: %s"
                % (installer, line, kind, rel, NOTE, sorted(BRAIN_DIRS if kind == "brain" else SRC_DIRS)[:12]))


def test_every_allowlist_entry_is_referenced_by_an_installer():
    """An allowlist nothing references is an author-supplied claim (conventions-015/023)."""
    used = {(l[2], l[3]) for l in LITERALS} | {(l[2], _dir_base(l[3])) for l in LITERALS if "*" in l[3]}
    unused = ([("brain", k) for k in RUNTIME_BRAIN if ("brain", k) not in used]
              + [("pkg", k) for k in OPTIONAL_PKG if ("pkg", k) not in used]
              + [("home", k) for k in CLAUDE_HOME_MEMBERS if ("home", k) not in used])
    assert unused == [], "allowlist entries no installer references (delete them or say why): %s" % unused


def test_the_manifest_is_the_oracle():
    """The oracle must be the lay manifest, not the identity fallback: the fallback exists
    so the parent commit's wrong literals are still NAMED, but a tree without a manifest
    has not bound its installers to anything."""
    assert MANIFEST.is_file(), NOTE
